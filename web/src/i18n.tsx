type Lang = 'en' | 'fr';
const I18nContext = createContext<{ t: Dict; lang: Lang; toggle: () => void }>({ t: en, lang: 'en', toggle: () => {} });

export function I18nProvider({ children }: { children: ReactNode }) {
  const initial = load<Lang>('lang') ?? (navigator.language.startsWith('fr') ? 'fr' : 'en');
  const [lang, setLang] = useState<Lang>(initial);
  document.documentElement.lang = lang === 'fr' ? 'fr-CA' : 'en-CA';
  const toggle = () => {
    const next = lang === 'en' ? 'fr' : 'en';
    save('lang', next);
    setLang(next);
  };
  return <I18nContext.Provider value={{ t: lang === 'fr' ? fr : en, lang, toggle }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
